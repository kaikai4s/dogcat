export function buildArchitecture() {
  const source = readFileSync(PLAN_URL, 'utf8');
  const root = group(null, 'Pine Courtyard Villa');
  const structures = {};
  const rooms = roomSpecs.map(([level, id, name, x, z, description, featured]) => ({ id, name, level, position: [x, ELEVATION[level] + 1.15, z], description, featured: Boolean(featured) }));

  for (let level = 1; level <= 3; level++) {
    const plan = readPlan(source, level);
    const floor = group(root, 'F' + level);
    const exterior = group(floor, 'Exterior');
    const walls = group(floor, 'Walls');
    const structure = group(floor, 'Structure');
    group(floor, 'Furniture');
    structures[level] = structure;

    addFloorPlate(structure, level);
    plan.exterior.forEach((segment) => addExterior(exterior, segment, level));
    plan.interior.forEach((segment) => partition(walls, segment, level));
    plan.shaft.forEach((segment) => partition(walls, segment, level, true));
    screens(exterior, level);
    addLift(root, walls, level);
    rooms.push(
      { id: 'lift-' + level, name: '电梯', level, position: [8.02, ELEVATION[level] + 1.16, 1.55], description: '电梯可从任一楼层呼叫，轿厢沿同一井道停靠三层。', featured: true },
      { id: 'stairs-' + level, name: '双跑楼梯', level, position: [10, ELEVATION[level] + 1.18, 5.56], description: '两段木踏步以北侧半层平台连接，南侧与公共过厅相通。', featured: true },
    );
  }
  addStairs(structures, 1);
  addStairs(structures, 2);
  addRoof(root);
  flush(root);
  return { root, rooms };
}
