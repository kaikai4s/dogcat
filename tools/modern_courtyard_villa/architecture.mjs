const unitBox = new THREE.BoxGeometry(1, 1, 1);
const batches = new WeakMap();
const up = new THREE.Vector3(0, 1, 0);
const quaternion = new THREE.Quaternion();
const dim = new THREE.Vector3();
const pos = new THREE.Vector3();
const matrix = new THREE.Matrix4();

function group(parent, name) {
  const result = new THREE.Group();
  result.name = name;
  parent?.add(result);
  return result;
}

function batch(group, mat, geometry) {
  if (!batches.has(group)) batches.set(group, new Map());
  const set = batches.get(group);
  if (!set.has(mat)) set.set(mat, []);
  set.get(mat).push(geometry);
}

function cuboid(group, mat, x, y, z, w, h, d, yaw = 0) {
  if (w <= 0 || h <= 0 || d <= 0) return;
  matrix.compose(pos.set(x, y, z), quaternion.setFromAxisAngle(up, yaw), dim.set(w, h, d));
  batch(group, mat, unitBox.clone().applyMatrix4(matrix));
}

function bar(group, mat, a, b, w, d = w) {
  const delta = b.clone().sub(a);
  const length = delta.length();
  matrix.compose(pos.copy(a).add(b).multiplyScalar(.5), quaternion.setFromUnitVectors(up, delta.normalize()), dim.set(w, length, d));
  batch(group, mat, unitBox.clone().applyMatrix4(matrix));
}

function flush(group) {
  for (const [mat, geometries] of batches.get(group) || []) {
    const geometry = geometries.length === 1 ? geometries[0] : mergeGeometries(geometries);
    if (geometries.length !== 1) geometries.forEach((part) => part.dispose());
    const mesh = new THREE.Mesh(geometry, mat);
    mesh.name = mat.name;
    mesh.castShadow = mesh.receiveShadow = !mat.transparent;
    group.add(mesh);
  }
  batches.delete(group);
  group.children.forEach(flush);
}

// The SVG is generated by the concept drawing script. Unlike hand-transcribed walls,
// this keeps every opening width and position tied to the drawings reviewed by the user.
function enclosingGroup(svg, marker) {
  const start = svg.indexOf(marker);
  if (start < 0) throw new Error('Missing plan group: ' + marker);
  let depth = 0;
  const pieces = /<g\b[^>]*>|<\/g>/g;
  pieces.lastIndex = start;
  for (let match; (match = pieces.exec(svg));) {
    depth += match[0] === '</g>' ? -1 : 1;
    if (!depth) return svg.slice(start, pieces.lastIndex);
  }
  throw new Error('Unclosed plan group: ' + marker);
}

function segments(svg) {
  return Array.from(svg.matchAll(/<path d="M([-.\d]+) ([-.\d]+)([HV])([-.\d]+)" class="(shell-edge|wall|door|glazing)"\/>/g), ([, sx, sz, axis, end, kind]) => {
    const x = Number(sx), z = Number(sz), final = Number(end);
    const x1 = axis === 'H' ? final : x, z1 = axis === 'V' ? final : z;
    const length = Math.hypot(x1 - x, z1 - z);
    return { x, z, x1, z1, length, kind, dx: (x1 - x) / length, dz: (z1 - z) / length };
  });
}

function readPlan(svg, level) {
  const floor = enclosingGroup(svg, '<g id="floor-' + level + '"');
  const envelope = enclosingGroup(floor, '<g class="envelope">');
  const core = enclosingGroup(floor, '<g class="core">');
  const exterior = segments(envelope), interior = segments(floor.replace(envelope, '').replace(core, '')), shaft = segments(core);
  if (exterior.length < 18 || interior.length < 20 || shaft.length !== 6) throw new Error('Incomplete openings for floor ' + level);
  return { exterior, interior, shaft };
}

function along(group, mat, segment, offset, y0, y1, width, depth, side = 0) {
  const { x, z, dx, dz } = segment;
  cuboid(group, mat, x + dx * offset - dz * side, (y0 + y1) * .5, z + dz * offset + dx * side, width, y1 - y0, depth, -Math.atan2(dz, dx));
}

function solid(group, mat, segment, y0, y1, depth, offset = 0) {
  along(group, mat, segment, segment.length * .5, y0, y1, segment.length, depth, offset);
}

function sideOf(segment, far) {
  if (segment.dz) return segment.x === 0 ? -1 : 1;
  return segment.z === far ? -1 : 1;
}

function addExterior(group, segment, level) {
  const y = ELEVATION[level], top = CEILING[level], length = segment.length;
  const far = DEPTH[level], inside = sideOf(segment, far);
  const south = segment.dx && segment.z === far;
  const door = segment.kind === 'door';
  if (segment.kind === 'shell-edge') {
    solid(group, M.lime, segment, y, top, .22, inside * .11);
    solid(group, M.sill, segment, y, y + .14, .025, inside * -.0125);
    solid(group, M.woodPale, segment, y, y + .078, .03, inside * .23);
    return;
  }

  const privateGlass = (level === 2 && segment.z === 0 && segment.x > 13) || (level === 3 && segment.x === 16 && segment.z > 6.6);
  const low = y + (door ? .018 : privateGlass ? 1.33 : south ? .20 : level === 1 && segment.z === 0 ? .88 : .66);
  const high = Math.min(top - .18, y + (door ? 2.63 : 2.72));
  solid(group, M.lime, segment, y, low, .22, inside * .11);
  solid(group, M.lime, segment, high, top, .22, inside * .11);
  if (!door) solid(group, M.sill, segment, low - .045, low + .012, .28, inside * .07);

  const center = inside * .083, jamb = .065;
  solid(group, M.frame, segment, low, low + jamb, .105, center);
  solid(group, M.frame, segment, high - jamb, high, .105, center);
  const panes = door ? 2 : Math.max(1, Math.round(length / 1.16));
  for (let index = 0; index <= panes; index++) {
    const u = THREE.MathUtils.clamp((length * index) / panes, jamb * .5, length - jamb * .5);
    along(group, M.frame, segment, u, low, high, jamb, .105, center);
  }
  for (let index = 0; index < panes; index++) {
    along(group, privateGlass ? M.privacy : M.glazing, segment, length * (index + .5) / panes, low + jamb, high - jamb, length / panes - jamb, .021, center);
  }
  if (door) for (const delta of [-.115, .115]) {
    for (const facing of [-1, 1]) along(group, M.steel, segment, length * .5 + delta, y + .82, y + 1.18, .035, .035, center + facing * .085);
  }
}

function partition(walls, segment, level, lift = false) {
  const y = ELEVATION[level], top = CEILING[level], span = segment.length;
  const thick = lift ? .16 : .15;
  if (segment.kind === 'wall') {
    solid(walls, M.inside, segment, y, top, thick);
    for (const side of [-1, 1]) solid(walls, M.woodPale, segment, y, y + .083, .015, side * (thick * .5 + .006));
    return;
  }
  const atLift = lift || (segment.x === 8.5 && segment.dz && segment.z === .93);
  const height = atLift ? 2.27 : span > 2 ? 2.53 : 2.24;
  const frame = atLift ? M.steel : M.walnut;
  solid(walls, M.inside, segment, y + height, top, thick);
  solid(walls, frame, segment, y + height - .055, y + height, thick + .035);
  for (const end of [.027, span - .027]) along(walls, frame, segment, end, y + .01, y + height, .054, thick + .035);

  // A pivoted timber leaf sits against the room side and leaves a walkable opening.
  if (!atLift && span < 1.55) {
    const side = segment.dz ? (segment.x >= 12 ? -1 : 1) : -1;
    const pivot = .067, width = span - .13, yaw = -Math.atan2(segment.dz, segment.dx) - side * Math.PI * .46;
    const x = segment.x + segment.dx * pivot - segment.dz * side * .08 + Math.cos(yaw) * width * .5;
    const z = segment.z + segment.dz * pivot + segment.dx * side * .08 - Math.sin(yaw) * width * .5;
    cuboid(walls, segment.x === 12.9 && segment.z === 9.15 && level === 1 ? M.mahogany : M.wood, x, y + 1.065, z, width, 2.06, .044, yaw);
    const grip = width * .41;
    cuboid(walls, M.steel, x + Math.cos(yaw) * grip, y + 1.03, z - Math.sin(yaw) * grip, .085, .028, .079, yaw);
  }
}

function slab(group, mat, rectangle, y0, y1, holes = []) {
  const [x0, x1, z0, z1] = rectangle;
  const xs = [x0, x1], zs = [z0, z1];
  for (const [l, r, n, s] of holes) {
    for (const x of [l, r]) if (x > x0 && x < x1) xs.push(x);
    for (const z of [n, s]) if (z > z0 && z < z1) zs.push(z);
  }
  xs.sort((a, b) => a - b);
  zs.sort((a, b) => a - b);
  for (let ix = 1; ix < xs.length; ix++) for (let iz = 1; iz < zs.length; iz++) {
    const x = (xs[ix - 1] + xs[ix]) * .5, z = (zs[iz - 1] + zs[iz]) * .5;
    if (!holes.some(([a, b, c, d]) => x > a && x < b && z > c && z < d)) {
      cuboid(group, mat, x, (y0 + y1) * .5, z, xs[ix] - xs[ix - 1], y1 - y0, zs[iz] - zs[iz - 1]);
    }
  }
}

