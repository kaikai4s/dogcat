import { copyFile, mkdir, readFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import { build } from 'esbuild'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const license = resolve(dirname(require.resolve('three')), '../LICENSE')
const output = resolve(here, '../../miniprogram/packageManor3d/vendor')

// These adaptations are scoped to the vendored modules. Never install fake DOM
// objects or mutate globals in the mini-program process.
const nativePatches = {
  'GLTFLoader.js': [
    ['const plugins = {};\n\t\tconst textDecoder = new TextDecoder();',
      'const plugins = {};\n\t\tconst textDecoder = data instanceof ArrayBuffer ? new TextDecoder() : null;']
  ],
  'WebGLCapabilities.js': [
    ["typeof WebGL2RenderingContext !== 'undefined' && gl.constructor.name === 'WebGL2RenderingContext'",
      "typeof gl.texStorage2D === 'function' && typeof gl.createVertexArray === 'function' && typeof gl.drawElementsInstanced === 'function'"]
  ],
  'WebGLAnimation.js': [
    ['context.cancelAnimationFrame( requestId );', 'if ( context !== null && requestId !== null ) context.cancelAnimationFrame( requestId );']
  ],
  'skinning_pars_vertex.glsl.js': [
    ['uniform highp sampler2D boneTexture;', `uniform highp sampler2D boneTexture;
	#if __VERSION__ < 300
		uniform highp float boneTextureSize;
	#endif`],
    ['int size = textureSize( boneTexture, 0 ).x;', `#if __VERSION__ >= 300
		int size = textureSize( boneTexture, 0 ).x;`],
    ['return mat4( v1, v2, v3, v4 );', `#else
		float j = i * 4.0;
		float x = mod( j, boneTextureSize );
		float y = floor( j / boneTextureSize );
		float stepX = 1.0 / boneTextureSize;
		vec2 uv = ( vec2( x, y ) + 0.5 ) * stepX;
		vec4 v1 = texture2D( boneTexture, uv );
		vec4 v2 = texture2D( boneTexture, uv + vec2( stepX, 0.0 ) );
		vec4 v3 = texture2D( boneTexture, uv + vec2( 2.0 * stepX, 0.0 ) );
		vec4 v4 = texture2D( boneTexture, uv + vec2( 3.0 * stepX, 0.0 ) );
		#endif

		return mat4( v1, v2, v3, v4 );`]
  ],
  'WebGLRenderer.js': [
    ["p_uniforms.setValue( _gl, 'boneTexture', skeleton.boneTexture, textures );", `p_uniforms.setValue( _gl, 'boneTexture', skeleton.boneTexture, textures );
						if ( !capabilities.isWebGL2 ) p_uniforms.setValue( _gl, 'boneTextureSize', skeleton.boneTexture.image.width );`]
  ]
}

await mkdir(output, { recursive: true })
await build({
  absWorkingDir: here,
  entryPoints: ['runtime.mjs'],
  outfile: join(output, 'three-runtime.js'),
  platform: 'neutral',
  mainFields: ['module', 'main'],
  format: 'cjs',
  target: 'es2018',
  bundle: true,
  minify: true,
  legalComments: 'none',
  banner: { js: '/* Three.js r162, MIT license. Generated by tools/manor_mini_runtime/build.mjs. */' },
  plugins: [{
    name: 'manor-native-webgl',
    setup(plugin) {
      plugin.onResolve({ filter: /^three$/ }, () => ({ path: resolve(dirname(require.resolve('three')), '../src/Three.js') }))
      plugin.onLoad({ filter: /(?:GLTFLoader|WebGLCapabilities|WebGLAnimation|WebGLRenderer|skinning_pars_vertex\.glsl)\.js$/ }, async ({ path }) => {
        const patches = nativePatches[path.split(/[\\/]/).pop()]
        let contents = await readFile(path, 'utf8')
        for (const [before, after] of patches) {
          if (contents.split(before).length !== 2) throw new Error('Review the Three.js patch for ' + path)
          contents = contents.replace(before, after)
        }
        return { contents, loader: 'js', resolveDir: dirname(path) }
      })
    }
  }]
})
await copyFile(license, join(output, 'THREE-LICENSE.txt'))
