const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../../miniprogram')
const list = path.join(root, 'pages/client/sitters/list')

test('sitter hero keeps location and map as separate compact actions', () => {
  const markup = fs.readFileSync(path.join(list, 'index.wxml'), 'utf8')
  const styles = fs.readFileSync(path.join(list, 'index.wxss'), 'utf8')
  const icons = fs.readFileSync(path.join(root, 'assets/fonts/remixicon.wxss'), 'utf8')

  assert.match(markup, /class="sitter-hero-actions"/)
  assert.match(markup, /class="sitter-location-bar" bindtap="updateLocation"/)
  assert.match(markup, /class="sitter-map-btn" bindtap="openMap"/)
  assert.match(markup, /ri-map-pin-line/)
  assert.match(icons, /\.ri-map-pin-line:before/)
  assert.doesNotMatch(markup, /地图找宠托师 · 按小区查看/)
  assert.doesNotMatch(markup, /location-address|location-change-tag/)
  assert.match(styles, /\.sitter-hero-actions\s*\{[^}]*display:\s*flex;[^}]*min-width:\s*0/s)
  assert.match(styles, /\.sitter-list-page \.sitter-hero\s*\{[^}]*rgba\(255, 248, 236, 0\) 100%/s)
  assert.match(styles, /\.sitter-list-page \.sitter-hero\s*\{[^}]*margin:\s*0 -30rpx;/s)
  assert.match(styles, /\.sitter-map-btn\s*\{[^}]*height:\s*64rpx;[^}]*background:\s*transparent;[^}]*white-space:\s*nowrap;/s)
  assert.match(styles, /\.sitter-location-bar\s*\{[^}]*height:\s*64rpx;/s)
  assert.match(styles, /\.location-name\s*\{[^}]*min-width:\s*0;/s)
})
