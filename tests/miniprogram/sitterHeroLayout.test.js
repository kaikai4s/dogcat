const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '../../miniprogram')
const list = path.join(root, 'pages/client/sitters/list')

test('sitter list keeps a compact header, full-width search, and a floating map entry', () => {
  const markup = fs.readFileSync(path.join(list, 'index.wxml'), 'utf8')
  const styles = fs.readFileSync(path.join(list, 'index.wxss'), 'utf8')
  const icons = fs.readFileSync(path.join(root, 'assets/fonts/remixicon.wxss'), 'utf8')

  assert.match(markup, /class="sitter-hero-actions"/)
  assert.match(markup, /class="sitter-location-bar" bindtap="updateLocation"/)
  assert.match(markup, /class="sitter-map-btn \{\{themeClass\}\} \{\{fontClass\}\}" bindtap="openMap"/)
  assert.ok(markup.indexOf('class="sitter-location-bar"') < markup.indexOf('class="sitter-hero-title"'))
  assert.ok(markup.indexOf('class="sitter-map-btn') > markup.indexOf('</dovlin-refresh>'))
  assert.ok(markup.indexOf('class="sitter-map-btn') < markup.indexOf('class="bottom-nav"'))
  assert.doesNotMatch(markup, /hero-badge|sitter-hero-subtitle|hero-count/)
  assert.match(markup, /ri-map-pin-line/)
  assert.match(markup, /ri-map-pin-2-fill/)
  assert.match(icons, /\.ri-map-pin-2-fill:before/)
  assert.doesNotMatch(markup, /地图找宠托师 · 按小区查看/)
  assert.doesNotMatch(markup, /location-address|location-change-tag/)
  assert.match(styles, /\.sitter-hero-actions\s*\{[^}]*display:\s*flex;[^}]*min-width:\s*0/s)
  assert.match(styles, /\.sitter-list-page \.sitter-hero\s*\{[^}]*rgba\(255, 248, 236, 0\) 100%/s)
  assert.match(styles, /\.sitter-list-page \.sitter-hero\s*\{[^}]*margin:\s*0 -30rpx;/s)
  assert.match(styles, /\.sitter-search-wrap\s*\{[^}]*display:\s*flex;/s)
  assert.match(styles, /\.sitter-page\s*\{[^}]*padding-bottom:\s*calc\(280rpx \+ env\(safe-area-inset-bottom\)\)/s)
  assert.match(styles, /\.sitter-map-btn\s*\{[^}]*position:\s*fixed;[^}]*bottom:\s*calc\(156rpx \+ env\(safe-area-inset-bottom\)\);[^}]*width:\s*248rpx;/s)
  assert.match(styles, /\.search-input\s*\{[^}]*flex:\s*1;[^}]*width:\s*0;[^}]*min-width:\s*0;/s)
  assert.match(styles, /\.sitter-location-bar\s*\{[^}]*height:\s*52rpx;/s)
  assert.match(styles, /\.location-name\s*\{[^}]*min-width:\s*0;/s)
})
