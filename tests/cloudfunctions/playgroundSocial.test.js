const test=require('node:test')
const assert=require('node:assert/strict')
const {createCollectionStore}=require('./helpers')
const world=require('../../cloudfunctions/api/services/playground-world')
const createShared=require('../../cloudfunctions/api/services/playground-shared')
const {playerId}=require('../../cloudfunctions/api/services/playground-live')
const {transaction}=require('../../cloudfunctions/api/services/playground-transaction')
const {dayEnd}=require('../../cloudfunctions/api/services/playground-social')
async function fixture() {
  let time=Date.parse('2026-10-18T15:59:00Z')
  const users=['a','b','c'].map((openid,i)=>({_id:'u_'+openid,openid,nickname:['凯大大','小红','访客'][i],residentialCommunity:{name:i===2?'B小区':'A小区'}}))
  const pets=users.map((u)=>({_id:'pet_'+u.openid,openid:u.openid,name:'豆豆',species:'dog'}))
  const db=createCollectionStore({users,pets}),context={db,nowMs:()=>time,nowText:()=>new Date(time).toISOString(),safeText:(s)=>s||'',getUser:async(id)=>db.state.users.find((u)=>u.openid===id)}
  const plots=world.create(context),shared=createShared(context),social=shared.social
  await plots.claim('a',users[0],{x:280,z:280})
  await plots.claim('b',users[1],{x:700,z:700})
  await plots.claim('c',users[2],{x:280,z:280})
  const scenes={}
  for(const id of ['a','b','c'])scenes[id]=await shared.enter(id,users.find((u)=>u.openid===id),id==='c'?{community:users[0].residentialCommunity}:{},pets.filter((p)=>p.openid===id))
  const auth=(id)=>({session:scenes[id].session,sceneId:scenes[id].sceneId})
  const position=(id,x,z)=>db.collection('pet_playground_plots').doc(playerId(id)).update({data:{position:{x,z}}})
  return {db,users,plots,shared,social,scenes,auth,position,now:()=>time,advance:(n)=>{time+=n},context}
}
test('transaction conflicts retry with fresh reads, unrelated errors are not retried, exhaustion is readable',async()=>{
  let attempts=0,waits=0
  const db={runTransaction:async(fn)=>{attempts++;if(attempts<3)throw new Error('ResourceUnavailable.TransactionConflict Transaction is conflict');return fn({value:7})}}
  assert.equal(await transaction(db,async(tx)=>tx.value,{wait:async()=>{waits++}}),7)
  assert.equal(attempts,3);assert.equal(waits,2)
  attempts=0
  await assert.rejects(()=>transaction({runTransaction:async()=>{attempts++;throw new Error('permission denied')}},()=>{},{wait:async()=>{}}),/permission denied/)
  assert.equal(attempts,1)
  await assert.rejects(()=>transaction({runTransaction:async()=>{throw new Error('TransactionConflict')}},()=>{},{wait:async()=>{}}),/操作人数较多/)
})
