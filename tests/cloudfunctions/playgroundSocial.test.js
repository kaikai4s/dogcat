test('friendship requires proximity and recipient approval, grants reciprocal entry, and removal revokes both sides',async()=>{
  const f=await fixture()
  await assert.rejects(()=>f.social.request('a',{...f.auth('a'),playerId:playerId('b')}),/走近/)
  await f.position('a',380,380);await f.position('b',382,380)
  await f.social.request('a',{...f.auth('a'),playerId:playerId('b')})
  const inbox=await f.social.state('b'),id=inbox.incoming[0].id
  await assert.rejects(()=>f.social.respond('c',{requestId:id,accept:true}),/不存在/)
  assert.equal((await f.social.state('a')).friends.length,0)
  await f.social.respond('b',{requestId:id,accept:true})
  assert.equal((await f.social.state('a')).friends[0].id,playerId('b'))
  assert.equal((await f.social.state('b')).friends[0].id,playerId('a'))
  const aHome=await f.plots.own('a'),bHome=await f.plots.own('b')
  const plots=[{...aHome,_id:aHome.plotId},{...bHome,_id:bHome.plotId}]
  assert.equal((await f.social.access('a',plots)).length,2)
  assert.equal((await f.social.access('b',plots)).length,2)
  await f.social.removeFriend('a',{playerId:playerId('b')})
  assert.equal((await f.social.access('a',plots)).length,1)
  assert.equal((await f.social.access('b',plots)).length,1)
})
test('strangers cannot cross a gate; approved visits expire at Beijing midnight and eject an inside visitor',async()=>{
  const f=await fixture(),home=await f.plots.own('a')
  await f.position('c',280,338)
  f.advance(1000)
  await assert.rejects(()=>f.shared.sync('c',{...f.auth('c'),seq:1,position:{x:280,z:334}}),/需要好友或访问许可/)
  await f.social.request('c',{...f.auth('c'),type:'visit',playerId:playerId('a'),plotId:home.plotId})
  const inbox=await f.social.state('a')
  assert.equal(inbox.incoming.length,1)
  await f.social.request('c',{...f.auth('c'),type:'visit',playerId:playerId('a'),plotId:home.plotId})
  assert.equal((await f.social.state('a')).incoming.length,1)
  await f.social.respond('a',{requestId:inbox.incoming[0].id,accept:true})
  const visit=(await f.social.state('c')).visits[home.plotId]
  assert.equal(visit.expiresAt,Date.parse('2026-10-18T16:00:00Z'))
  await f.shared.sync('c',{...f.auth('c'),seq:1,position:{x:280,z:334}})
  f.advance(visit.expiresAt-f.now()+1)
  const result=await f.shared.sync('c',{...f.auth('c'),seq:2,position:{x:280,z:330}})
  assert.equal(result.corrected,true)
  assert.ok(Math.abs(result.position.x-280)>=56.8 || Math.abs(result.position.z-280)>=56.8)
  await assert.rejects(()=>f.plots.fillBowl('c',{plotId:home.plotId}),/只能给自己/)
})
