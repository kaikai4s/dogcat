test('live projection rejects delayed writes and a yard rebuilt in the same cell beats the deletion',async()=>{
  const f=await fixture(),handler=require('../../cloudfunctions/api/handlers/playground')(f.context)
  const live=require('../../cloudfunctions/api/services/playground-live')(f.context)
  await live.publish('test',{id:'neighbor',kind:'presence',position:{x:10,z:10}},{epoch:10,seq:2})
  await live.publish('test',{id:'neighbor',kind:'presence',position:{x:1,z:1}},{epoch:10,seq:1})
  const publicRow=(scene,id)=>f.db.state.pet_playground_live.filter((r)=>r.kind==='scene'&&r.communityId===scene).map((r)=>r.records&&r.records[id]).find(Boolean)
  assert.equal(publicRow('test','neighbor').position.x,10)
  const plot=await f.plots.own('a')
  await handler('a','demolishPlot',{plotId:plot.plotId,sceneId:f.scenes.a.sceneId})
  assert.equal(publicRow(f.scenes.a.sceneId,playerId('a')).deleted,true)
  await live.publish(f.scenes.a.sceneId,{id:playerId('a'),kind:'presence',position:{x:1,z:1}},{epoch:1,seq:99})
  assert.equal(publicRow(f.scenes.a.sceneId,playerId('a')).deleted,true)
  await handler('a','claimPlot',{x:280,z:280,sceneId:f.scenes.a.sceneId})
  const scene=await handler('a','enterScene',{})
  assert.equal(scene.scene.hasAvatar,true)
  assert.equal(publicRow(f.scenes.a.sceneId,playerId('a')).deleted,undefined)
  assert.equal(publicRow(f.scenes.a.sceneId,plot.plotId).deleted,undefined)
})
