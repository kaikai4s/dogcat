test('memorial applications deliver one admin subscription and suppress notices already reviewed', async () => {
  const sent = []
  const { call, db, context } = fixture({ platform_configs: [{ _id: 'settings', key: 'system_settings', value: {
    subscription: { enabled: true, templates: { adminPendingAudit: 'audit-template-id' } }
  } }] }, async payload => { sent.push(payload); return { errCode: 0 } })
  await call('a', 'submit', application())
  await call('a', 'submit', application())
  const deliveries = db.state.subscription_logs.filter(row => row.delivery)
  assert.equal(deliveries.length, 1)
  assert.equal(deliveries[0].auditType, 'memorial_application')
  await context.retryFailedSubscriptions()
  assert.equal(sent.length, 1)
  assert.equal(sent[0].page, 'pages/admin/memorial/index')
  assert.equal(sent[0].templateId, 'audit-template-id')
  assert.equal(sent[0].data.thing2.value, '时光小筑申请')
  const distant = available.findIndex(p => Math.abs(p.x - available[0].x) >= 128 || Math.abs(p.y - available[0].y) >= 128)
  const { id } = await call('b', 'submit', application(distant))
  await call('admin', 'review', { id, status: 'approved' })
  await context.retryFailedSubscriptions()
  assert.equal(sent.length, 1, 'a resolved application must not send a stale reminder')
})

test('larger footprints reject blocked scenery and serialize adjacent claims without relocating old memorials', async () => {
  const { call, db } = fixture()
  const a = available[0], b = available.find(p => p.id !== a.id && Math.abs(p.x - a.x) < 128 && Math.abs(p.y - a.y) < 128)
  assert.ok(b)
  const claims = await Promise.allSettled([call('a', 'submit', application()), call('b', 'submit', application(available.indexOf(b)))])
  assert.equal(claims.filter(r => r.status === 'fulfilled').length, 1)
  assert.match(claims.find(r => r.status === 'rejected').reason.message, /陪伴空间/)
  assert.ok((await call('a', 'world')).occupied.includes(b.id))
  const blocked = world.cells.find(p => !available.some(a => a.id === p.id))
  await assert.rejects(call('b', 'submit', application(0, { plotId: blocked.id })), /空间/)
  const row = db.state.platform_configs.find(p => p.key === 'memorial_application')
  await call('admin', 'review', { id: row._id, status: 'rejected', reason: '重新选择' })
  assert.deepEqual((await call('a', 'world')).occupied, [])
})

test('garden create/edit names are unique, versioned, idempotent and permission protected', async () => {
  const {call,db}=fixture()
  const form={name:'星光纪念园',accepting:true,requestId:'garden_request_01'}
  await assert.rejects(call('a','createGarden',form),/管理员|权限/)
  const created=await call('admin','createGarden',form)
  assert.deepEqual(await call('admin','createGarden',form),created)
  await assert.rejects(call('admin','createGarden',{...form,name:'另一个名字'}),/内容已改变/)
  await assert.rejects(call('admin','createGarden',{...form,requestId:'garden_request_02'}),/同名/)
  await assert.rejects(call('admin','createGarden',{...form,name:'时光纪念园',requestId:'garden_request_03'}),/同名/)
  const edit={id:created.id,revision:1,name:'月光纪念园',accepting:false}
  const changed=await call('admin','updateGarden',edit)
  assert.equal(changed.revision,2); assert.equal(changed.accepting,false)
  assert.deepEqual(await call('admin','updateGarden',edit),changed)
  await assert.rejects(call('admin','updateGarden',{...edit,name:'过期修改'}),/更新/)
  assert.equal(db.state.pet_memorial_live.find(d=>d._id==='world_'+created.id).revision,2)
  const list=await call('a','listGardens')
  assert.deepEqual(list.list.map(g=>g.name),['时光纪念园','月光纪念园'])
})
