const test = require('node:test')
const assert = require('node:assert/strict')
const { createCollectionStore } = require('./helpers')
const createContext = require('../../cloudfunctions/api/services/context')
const world = require('../../cloudfunctions/api/config/memorial-world.json')
function fixture(extra = {}) {
  const db = createCollectionStore({ users: ['a', 'b', 'admin'].map(openid => ({ _id: openid, openid, nickname: openid, roles: [openid === 'admin' ? 'admin' : 'client'], status: 'active' })), ...extra })
  const context = createContext({ db, cloud: { openapi: { security: { msgSecCheck: async () => ({ errCode: 0, result: { suggest: 'pass' } }) } } } })
  const handler = require('../../cloudfunctions/api/handlers/memorial')(context)
  const call = (who, action, data = {}) => context.runAdminRequest('memorial', action, data, () => handler(who, action, data))
  return { db, call, context }
}
const application = (i = 0, extra = {}) => ({ requestId: 'request_' + i, version: world.version, plotId: world.cells[i].id, petName: '小白', epitaph: '永远想念你', date: '2025-01-01', ...extra })
test('submission reserves once, notifies admins and never exposes pending text or applicant identity publicly', async () => {
  const { db, call } = fixture()
  const result = await call('a', 'submit', application())
  assert.deepEqual(await call('a', 'submit', application()), result)
  assert.equal(db.state.platform_configs.filter(p => p.key === 'memorial_application').length, 1)
  assert.equal(db.state.admin_notifications.length, 1)
  assert.equal(db.state.admin_notifications[0].actionUrl, '/pages/admin/memorial/index')
  const publicWorld = await call('b', 'world')
  assert.deepEqual(publicWorld.occupied, [world.cells[0].id]); assert.deepEqual(publicWorld.memorials, [])
  assert.equal((await call('b', 'listMine')).list.length, 0)
  assert.equal((await call('a', 'listMine')).list[0].petName, '小白')
  await assert.rejects(call('a', 'submit', application(0, { epitaph: '改变内容' })), /内容已改变/)
})
test('racing applicants cannot claim the same plot; duplicate pet applications are rejected', async () => {
  const { call } = fixture()
  const results = await Promise.allSettled([call('a', 'submit', application()), call('b', 'submit', application())])
  assert.equal(results.filter(r => r.status === 'fulfilled').length, 1)
  assert.match(results.find(r => r.status === 'rejected').reason.message, /选走/)
  await assert.rejects(call('a', 'submit', application(1)), /已有/)
})
test('approval publishes the canonical fixed-size plot and sends one owner result; repeated review is idempotent', async () => {
  const { db, call } = fixture()
  const { id } = await call('a', 'submit', application())
  await assert.rejects(call('b', 'review', { id, status: 'approved' }), /管理员|权限/)
  await call('admin', 'review', { id, status: 'approved' })
  await call('admin', 'review', { id, status: 'approved' })
  const result = await call('b', 'world')
  assert.equal(result.memorials[0].x, world.cells[0].x)
  assert.equal(result.memorials[0].name, '小白')
  assert.equal(JSON.stringify(result).includes('ownerOpenid'), false)
  assert.equal(db.state.system_notifications.length, 1)
  assert.equal(db.state.system_notifications[0].targetOpenid, 'a')
  assert.equal(db.state.admin_notifications[0].resolved, true)
  assert.equal((await call('admin', 'listAdmin', { pendingCountsOnly: true })).pendingCount, 0)
  await assert.rejects(call('admin', 'review', { id, status: 'rejected', reason: '冲突操作' }), /已被处理/)
})
test('rejection releases the plot and allows corrected reapplication without duplicate notifications', async () => {
  const { call, db } = fixture()
  const { id } = await call('a', 'submit', application())
  await assert.rejects(call('admin', 'review', { id, status: 'rejected' }), /原因/)
  await call('admin', 'review', { id, status: 'rejected', reason: '请补充寄语' })
  assert.deepEqual((await call('a', 'world')).occupied, [])
  await call('a', 'submit', application(0, { requestId: 'new_request', epitaph: '补充后的寄语' }))
  assert.equal(db.state.admin_notifications.length, 2)
})
test('server rejects fake plots, stale versions, future dates and enforces delegated review permissions', async () => {
  const { call } = fixture({ admin_access_config: [{ _id: 'policy', enabled: true, ownerOpenid: 'owner' }],
    admin_memberships: [{ _id: 'admin', groupIds: ['read'] }], admin_groups: [{ _id: 'read', enabled: true, permissions: ['memorial.listAdmin'] }] })
  await assert.rejects(call('a', 'submit', application(0, { plotId: 'anything' })), /墓位/)
  await assert.rejects(call('a', 'submit', application(0, { version: 'old' })), /变化/)
  await assert.rejects(call('a', 'submit', application(0, { date: '2999-01-01' })), /日期/)
  const { id } = await call('b', 'submit', application())
  assert.equal((await call('admin', 'listAdmin')).list.length, 1)
  await assert.rejects(call('admin', 'review', { id, status: 'approved' }), /权限/)
})
