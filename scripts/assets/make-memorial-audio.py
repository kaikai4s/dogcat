"""Original deterministic synthesized garden music and effects; no downloaded recordings.

20-second C-major/add9 arpeggio, 8 bars at 96 BPM. Decays wrap around the
loop boundary; periodic ambient pad has matching phase at both ends.
"""
from pathlib import Path
import json
import wave
import hashlib
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'miniprogram/packageMemorial/assets/audio'
RATE = 22050


def save(name, samples):
    assert np.isfinite(samples).all()
    peak = float(np.max(np.abs(samples)))
    assert 0 < peak < 1, (name, peak)
    data = np.round(samples * 32767).astype('<i2').tobytes()
    target = OUT / (name + '.wav')
    with wave.open(str(target), 'wb') as output:
        output.setnchannels(1)
        output.setsampwidth(2)
        output.setframerate(RATE)
        output.writeframes(data)
    return {'duration': len(samples) / RATE, 'peak': peak, 'rms': float(np.sqrt(np.mean(samples ** 2))),
            'sha256': hashlib.sha256(target.read_bytes()).hexdigest(), 'bytes': target.stat().st_size}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    duration = 20
    music = np.zeros(duration * RATE)
    t = np.arange(len(music)) / RATE
    chords = [[48, 55, 60, 64, 67, 74], [45, 52, 57, 60, 64, 71],
              [41, 48, 53, 57, 60, 67], [43, 50, 55, 59, 62, 69]]
    for bar in range(8):
        chord = chords[bar % 4]
        for beat, tone in enumerate([0, 2, 3, 5]):
            freq = 440 * 2 ** ((chord[tone] - 69) / 12)
            nt = np.arange(RATE * 4) / RATE
            envelope = (1 - np.exp(-nt * 90)) * np.exp(-nt * 1.65)
            note = envelope * (np.sin(2 * np.pi * freq * nt) +
                               .23 * np.sin(2 * np.pi * freq * 2 * nt) * np.exp(-nt * 2) +
                               .06 * np.sin(2 * np.pi * freq * 3 * nt) * np.exp(-nt * 3))
            start = round((bar * 2.5 + beat * .625) * RATE)
            for delay, amount in [(0, .095), (.19, .019), (.37, .012)]:
                indices = (np.arange(len(note)) + start + round(delay * RATE)) % len(music)
                music[indices] += note * amount
    for freq, amount in [(130.8, .009), (196, .007), (261.6, .004)]:
        periodic_freq = round(freq * duration) / duration
        music += amount * np.sin(2 * np.pi * periodic_freq * t) * (1 + .25 * np.sin(2 * np.pi * t / duration))
    music *= .65 / max(.65, np.max(np.abs(music)))
    # A soft, short shoe contact with a muted low thud and filtered grit.
    rng = np.random.default_rng(20261111)
    st = np.arange(round(RATE * .18)) / RATE
    noise = rng.normal(0, 1, len(st))
    noise = np.convolve(noise, np.ones(9) / 9, mode='same')
    step = (1 - np.exp(-st * 600)) * np.exp(-st * 36) * (.34 * noise + .18 * np.sin(2 * np.pi * 115 * st))
    step *= np.minimum(1, (st[-1] - st) / .02)
    ct = np.arange(round(RATE * .45)) / RATE
    chime = .15 * (np.sin(2 * np.pi * 659.25 * ct) + .3 * np.sin(2 * np.pi * 987.77 * ct))
    chime *= (1 - np.exp(-ct * 180)) * np.exp(-ct * 12) * np.minimum(1, (ct[-1] - ct) / .03)
    records = {name: save(name, data) for name, data in [('music', music), ('step', step), ('chime', chime)]}
    records['provenance'] = 'Original procedural synthesis; generated by scripts/assets/make-memorial-audio.py, no external audio samples.'
    records['loopBoundaryDelta'] = float(abs(music[0] - music[-1]))
    (OUT / 'manifest.json').write_text(json.dumps(records, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(records, indent=2))


if __name__ == '__main__':
    main()
